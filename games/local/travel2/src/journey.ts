export function chapterAt(progress: number) {
  return Math.min(
    chapters.length - 1,
    Math.max(0, Math.floor((Number.isFinite(progress) ? progress : 0) * chapters.length)),
  );
}

// Land after the camera transition, leaving room to explore even in the last chapter.
export function chapterProgress(index: number) {
  return (Math.min(chapters.length - 1, Math.max(0, index)) + 0.45) / chapters.length;
}

export function readStamps(raw: string | null): string[] {
  try {
    const value: unknown = JSON.parse(raw ?? '[]');
    return Array.isArray(value)
      ? [...new Set(value.filter((id): id is string => chapters.some((c) => c.id === id)))]
      : [];
  } catch {
    return [];
  }
}
